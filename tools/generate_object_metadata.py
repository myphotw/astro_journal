def type_description(obj: dict) -> str:
    name = obj.get("commonName") or obj.get("name") or obj.get("id")
    obj_type = obj.get("objectType") or obj.get("type") or "천체"
    constellation = obj.get("constellation") or ""
    if constellation and constellation != "-":
        return f"{constellation}에 위치한 {obj_type}. {name}."
    return f"{obj_type} · {name}."


def load_json(path: Path) -> list:
    return json.loads(path.read_text(encoding="utf-8"))


def main() -> None:
    metadata: dict[str, dict[str, str]] = {}

    for obj_id, (size, desc) in {**MESSIER_META, **EXTRA_META}.items():
        metadata[obj_id] = {"angularSize": size, "description": desc}

    messier = load_json(CATALOG_DIR / "messier.json")
    seestar = load_json(CATALOG_DIR / "seestar_catalog.json")

    for obj in messier + seestar:
        obj_id = obj["id"]
        if obj_id in metadata:
            continue
        metadata[obj_id] = {
            "description": type_description(obj),
        }

    OUTPUT.write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"Written {len(metadata)} entries to {OUTPUT}")
